# agents/watcher.py
# ==============================================================================
# وكيل المراقبة (The Watcher) - المسؤول عن:
#   1. فتح الاتصال بالكاميرا وبث الإطارات للنظام
#   2. إعادة الاتصال التلقائي إذا انقطع بث الكاميرا
# ==============================================================================

import cv2  # مكتبة OpenCV للتعامل مع الكاميرا والفيديو

class WatcherAgent:
    """
    وكيل الكاميرا:
    يفتح الاتصال بالكاميرا ويُرجع إطارات الفيديو باستمرار.
    إذا انقطع الاتصال يُعيد الاتصال تلقائياً دون توقف النظام.
    """

    def __init__(self, camera_index=0):
        # رقم الكاميرا المستخدمة (0 = الكاميرا الافتراضية للجهاز)
        self.camera_index = camera_index
        self.cap = None   # كائب الكاميرا (VideoCapture)
        self.connect()    # الاتصال بالكاميرا عند بدء التشغيل

    # ==============================================================================
    # الاتصال بالكاميرا وضبط الدقة
    # ==============================================================================
    def connect(self):
        """
        فتح اتصال بالكاميرا وضبط الدقة على 1280x720 (HD).
        يستخدم CAP_DSHOW (DirectShow) لأسرع استجابة على ويندوز.
        يُعيد True إذا نجح الاتصال، False إذا فشل.
        """
        # إغلاق أي اتصال قديم قبل فتح اتصال جديد
        if self.cap is not None:
            self.cap.release()

        # فتح الكاميرا بـ DirectShow لأفضل أداء على ويندوز
        self.cap = cv2.VideoCapture(self.camera_index, cv2.CAP_DSHOW)

        if self.cap.isOpened():
            # ضبط دقة الكاميرا (1280x720 = HD)
            self.cap.set(cv2.CAP_PROP_FRAME_WIDTH,  1280)
            self.cap.set(cv2.CAP_PROP_FRAME_HEIGHT, 720)
            print(f"✅ [Watcher] تم الاتصال بالكاميرا {self.camera_index} بنجاح (HD 1280x720).")
            return True

        print(f"⚠️ [Watcher] تعذر الاتصال بالكاميرا {self.camera_index}.")
        return False

    # ==============================================================================
    # الحصول على إطار جديد من الكاميرا
    # ==============================================================================
    def get_frame(self):
        """
        قراءة إطار جديد من الكاميرا.
        إذا فشلت القراءة يحاول إعادة الاتصال مرة واحدة تلقائياً.
        يُعيد: (True, frame) إذا نجح، أو (False, None) إذا فشل نهائياً.
        """
        # إذا لم تكن الكاميرا مفتوحة، حاول إعادة الاتصال
        if not self.cap or not self.cap.isOpened():
            if not self.connect():
                return False, None  # فشل الاتصال تماماً

        # قراءة إطار من الكاميرا
        ret, frame = self.cap.read()

        if not ret:
            # الإطار فارغ - محاولة إعادة الاتصال مرة واحدة
            print("⚠️ [Watcher] انقطع بث الكاميرا، جاري إعادة الاتصال...")
            self.connect()
            ret, frame = self.cap.read()

        return ret, frame

    # ==============================================================================
    # إغلاق الاتصال بالكاميرا وتحرير الموارد
    # ==============================================================================
    def release(self):
        """تحرير مورد الكاميرا عند إغلاق النظام"""
        if self.cap:
            self.cap.release()
            print("🛑 [Watcher] تم تحرير الكاميرا.")